/** Local YYYY-MM-DD for the filename (date-granular, matches the spec). */
export function reportDateStamp(d: Date = new Date()): string {
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${y}-${m}-${day}`;
}

const escapeHtml = (s: unknown): string =>
  String(s ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');

/* ───────────────────────── Chart capture (recharts SVG → PNG) ───────────────── */

/** Best-effort chart title from the SVG's surrounding card (heading or bold text). */
function deriveChartTitle(svg: Element): string | null {
  let el: Element | null = svg.parentElement;
  for (let i = 0; i < 6 && el; i++, el = el.parentElement) {
    const h = el.querySelector('h1,h2,h3,h4');
    const t = h?.textContent?.trim();
    if (t) return t;
  }
  // Fallback: a short bold/semibold label (HR cards use <p class="font-semibold">).
  el = svg.parentElement;
  for (let i = 0; i < 6 && el; i++, el = el.parentElement) {
    const cand = Array.from(el.querySelectorAll('p,span,div')).find((n) => {
      const cls = typeof n.className === 'string' ? n.className : (n.getAttribute('class') || '');
      const txt = (n.textContent || '').trim();
      return /font-(semibold|bold)/.test(cls) && txt.length > 1 && txt.length < 60 && !n.querySelector('svg');
    });
    if (cand) return (cand.textContent || '').trim();
  }
  return null;
}

/** Rasterise a self-contained SVG (recharts) to a white-background PNG data URL. */
async function svgToPng(svg: SVGSVGElement): Promise<string | null> {
  const rect = svg.getBoundingClientRect();
  const w = Math.max(1, Math.round(rect.width || Number(svg.getAttribute('width')) || 600));
  const h = Math.max(1, Math.round(rect.height || Number(svg.getAttribute('height')) || 300));

  const clone = svg.cloneNode(true) as SVGSVGElement;
  clone.setAttribute('width', String(w));
  clone.setAttribute('height', String(h));
  if (!clone.getAttribute('viewBox')) clone.setAttribute('viewBox', `0 0 ${w} ${h}`);
  clone.setAttribute('xmlns', 'http://www.w3.org/2000/svg');
  // Pin a font so SVG <text> rasterises consistently (recharts sets no family).
  const style = document.createElementNS('http://www.w3.org/2000/svg', 'style');
  style.textContent = 'text{font-family:Arial,Helvetica,sans-serif;}';
  clone.insertBefore(style, clone.firstChild);

  const xml = new XMLSerializer().serializeToString(clone);
  const src = 'data:image/svg+xml;charset=utf-8,' + encodeURIComponent(xml);

  const img = new Image();
  img.width = w;
  img.height = h;
  await new Promise<void>((resolve, reject) => {
    img.onload = () => resolve();
    img.onerror = () => reject(new Error('chart image load failed'));
    img.src = src;
  });

  const scale = 2; // retina-crisp in the PDF
  const canvas = document.createElement('canvas');
  canvas.width = w * scale;
  canvas.height = h * scale;
  const ctx = canvas.getContext('2d');
  if (!ctx) return null;
  ctx.scale(scale, scale);
  ctx.fillStyle = '#ffffff';
  ctx.fillRect(0, 0, w, h);
  ctx.drawImage(img, 0, 0, w, h);
  return canvas.toDataURL('image/png');
}

/**
 * Capture every recharts chart currently rendered under `root` as a titled PNG.
 * Skips any chart that fails to rasterise (the rest still export). Lucide icons
 * are plain <svg> too, but only recharts uses `.recharts-surface`, so icons are
 * never picked up.
 */
export async function captureRechartsImages(root: ParentNode = document): Promise<ReportChartImage[]> {
  if (typeof window === 'undefined') return [];
  const svgs = Array.from(root.querySelectorAll('svg.recharts-surface')) as SVGSVGElement[];
  const out: ReportChartImage[] = [];
  for (let i = 0; i < svgs.length; i++) {
    try {
      const dataUrl = await svgToPng(svgs[i]);
      if (dataUrl) out.push({ title: deriveChartTitle(svgs[i]) || `Chart ${i + 1}`, dataUrl });
    } catch {
      /* skip this chart, keep the rest */
    }
  }
  return out;
}

