'use client';

/**
 * Reusable Founder-dashboard PDF export — dependency-free.
 *
 * Builds a branded, presentation-ready report (SHAHI SOLUTIONS) from the data a
 * dashboard ALREADY has in memory (no extra API calls) and prints it to PDF via
 * a hidden iframe + the browser's native print engine. The report HTML uses
 * explicit hex colours (not the app's Tailwind classes), so it is unaffected by
 * Tailwind v4 `oklch` colours that break DOM-rasterisers like html2canvas.
 *
 * Charts are captured from the live recharts SVGs and embedded as PNG images
 * (recharts uses explicit hex colours, so SVG→canvas→PNG is safe). Non-SVG
 * "charts" (funnels, leaderboards) are exported by their underlying data as
 * tables by the caller.
 *
 * The same service powers Projects, Sales, Developers and HR — one workflow,
 * one design. Browser-only (guards on `typeof window`).
 */

export interface ReportKpi { label: string; value: string | number }
export interface ReportTable {
  title: string;
  columns: string[];
  rows: (string | number)[][];
  note?: string;
  /** Optional per-column alignment (index-matched to `columns`); omit ⇒ left. */
  align?: ('left' | 'right')[];
}
export interface ReportChartImage {
  title: string;
  dataUrl: string;
  /** Optional caption under the title (mirrors the dashboard card's subtitle). */
  subtitle?: string;
  /**
   * Optional legend. Recharts legends in this app are HTML siblings of the <svg>,
   * so they are NOT part of the captured image — pass the same data/colours the
   * chart was given and it is re-rendered here as crisp text (chart left, legend
   * right). Charts without a legend render exactly as before.
   */
  legend?: { label: string; value: string | number; color: string }[];
}
export interface ReportFilter { label: string; value: string }

export interface DashboardReport {
  /** Human title shown in the report header, e.g. "Projects Dashboard". */
  dashboardName: string;
  /** Filename stem, e.g. "Projects_Dashboard" → Projects_Dashboard_2026-06-30.pdf */
  fileBase: string;
  /** Logged-in Founder/Admin name for the "Generated By" line. */
  generatedBy: string;
  filters?: ReportFilter[];
  kpis: ReportKpi[];
  charts?: ReportChartImage[];
  tables?: ReportTable[];
}

